import {
  FITNESS_TREND,
  FITNESS_TREND_EMPTY,
  FITNESS_TREND_GYM_PRICED,
  FITNESS_TREND_LATE_PRICED,
  FITNESS_TREND_UNPRICED,
} from "@/tests/mocks/generated-pmc";
import { http } from "@/tests/mocks/handlers";
