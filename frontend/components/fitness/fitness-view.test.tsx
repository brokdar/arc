import { server } from "@/tests/mocks/server";

/**
 * uPlot, **run** and recorded.
 *
 * The real library draws into a real (jsdom) canvas — which is what lets the
 * empty and failed states assert that *no* canvas was mounted — and the
 * recording keeps what it was constructed with, the only honest way to read
 * back which lines it was told to draw: it owns its canvas and exposes
 * neither the series nor the data.
 */
const constructions = vi.hoisted(
  () => [] as { options: uPlot.Options; data: uPlot.AlignedData }[],
);

vi.mock("uplot", async (importOriginal) => {
  const actual = await importOriginal<{ default: typeof uPlot }>();
  const Real = actual.default;
  class Recording extends Real {
    constructor(
      options: uPlot.Options,
      data: uPlot.AlignedData,
      target: HTMLElement,
    ) {
      super(options, data, target);
      constructions.push({ options, data });
    }
  }
  return { ...actual, default: Recording };
});

vi.mock("next/link", () => ({
  default: ({
    href,
    children,
    ...props
  }: React.PropsWithChildren<{ href: string }>) => (
    <a href={href} {...props}>
      {children}
    </a>
  ),
}));

function renderFitness() {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { retry: false } },
  });
  return render(
    <QueryClientProvider client={queryClient}>
      <AthleteClock timezone={ATHLETE_TIMEZONE}>
        <FitnessView />
      </AthleteClock>
    </QueryClientProvider>,
  );
}

/** The series uPlot was handed, by label. */
function plotted(): Map<string, (number | null)[]> {
  const [latest] = constructions.slice(-1);
  if (!latest) {
    throw new Error("uPlot was never constructed");
  }
  const lines = new Map<string, (number | null)[]>();
  latest.options.series.forEach((series, index) => {
    if (index > 0 && typeof series.label === "string") {
      lines.set(
        series.label,
        Array.from(latest.data[index] ?? [], (value) => value ?? null),
      );
    }
  });
  return lines;
}

describe("FitnessView", () => {
  beforeEach(() => {
    constructions.length = 0;
  });

  it("draws fitness, fatigue and form from the computed series", async () => {
    const { container } = renderFitness();

    await screen.findByRole("figure", { name: /Fitness, fatigue and form/ });

    const lines = plotted();
    // The values the backend domain computed — the fixture is generated by
    // `just pmc-fixture`, never typed — reach the chart unchanged.
    expect(lines.get("Fitness (CTL)")).toEqual(
      FITNESS_TREND.points.map((point) => point.ctl.value),
    );
    expect(lines.get("Fatigue (ATL)")).toEqual(
      FITNESS_TREND.points.map((point) => point.atl.value),
    );
    expect(lines.get("Form (TSB)")).toEqual(
      FITNESS_TREND.points.map((point) => point.tsb.value),
    );
    expect(container.querySelector("canvas")).not.toBeNull();
  });

  it("says, in a named badge, that the number never changes the plan", async () => {
    renderFitness();

    const badge = await screen.findByRole("note", { name: "Display-only" });

    expect(badge).toHaveTextContent(
      "arc will never change your plan because of this number",
    );
    expect(DISPLAY_ONLY_SENTENCE).toBe(
      "arc will never change your plan because of this number",
    );
  });

  it("says fitness is still maturing, counted from the first session", async () => {
    renderFitness();

    // Day 40 of the generated history; CTL matures on day 97.
    expect(FITNESS_TREND.maturity.day).toBe(40);
    expect(
      await screen.findByText("Baseline maturing — day 40 of 97"),
    ).toBeInTheDocument();
  });

  it("shows today's numbers, each under its explanation", async () => {
    renderFitness();

    const readout = await screen.findByRole("region", { name: "Today" });
    const [last] = FITNESS_TREND.points.slice(-1);
    if (!last) throw new Error("the fixture has no points");
    expect(within(readout).getByText(last.ctl.value.toFixed(0))).toBeVisible();
    expect(within(readout).getByText(last.atl.value.toFixed(0))).toBeVisible();
    expect(
      within(readout).getAllByRole("note", { name: /CTL_d = / }),
    ).toHaveLength(1);
  });

  it("marks a day with an unpriced session, in words as well as on the chart", async () => {
    renderFitness();

    const served = rebased(FITNESS_TREND);
    const incomplete = served.points.filter((point) => point.load_incomplete);
    expect(incomplete).toHaveLength(1);
    const [day] = incomplete;
    if (!day) throw new Error("no incomplete day");

    const note = await screen.findByTestId("fitness-incomplete-days");
    expect(note).toHaveTextContent(
      `Load incomplete on ${formatDayMonth(day.local_date)}`,
    );
    // The chart names the text alternative as its description.
    const figure = screen.getByRole("figure", {
      name: /Fitness, fatigue and form/,
    });
    expect(figure).toHaveAccessibleDescription(
      expect.stringContaining(formatDayMonth(day.local_date)),
    );
    // And the canvas marks that day, and only that day, on the fatigue line
    // it left a session out of.
    const index = served.points.indexOf(day);
    const marks = plotted().get("Load incomplete") ?? [];
    expect(marks.flatMap((value, at) => (value === null ? [] : [at]))).toEqual([
      index,
    ]);
    expect(marks[index]).toBe(day.atl.value);
  });

  it("names the missing input when there is no session at all", async () => {
    server.use(
      http.get("/api/v1/fitness", ({ response }) =>
        response(200).json(rebased(FITNESS_TREND_EMPTY)),
      ),
    );
    const { container } = renderFitness();

    expect(
      await screen.findByText(/Record a ride with power or heart rate/),
    ).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Upload a ride" })).toHaveAttribute(
      "href",
      "/inbox",
    );
    expect(container.querySelector("canvas")).toBeNull();
    expect(constructions).toHaveLength(0);
  });

  it("renders a history nothing could price as not assessed, never zero", async () => {
    // The generated read: every session unpriced, so the domain's averages
    // are 0 on every day with no load behind them.
    expect(FITNESS_TREND_UNPRICED.points.length).toBeGreaterThan(0);
    expect(FITNESS_TREND_UNPRICED.maturity.ctl.first_priced_session).toBeNull();
    expect(FITNESS_TREND_UNPRICED.maturity.atl.first_priced_session).toBeNull();
    expect(FITNESS_TREND_UNPRICED.maturity.tsb.first_assessed).toBeNull();
    server.use(
      http.get("/api/v1/fitness", ({ response }) =>
        response(200).json(rebased(FITNESS_TREND_UNPRICED)),
      ),
    );
    const { container } = renderFitness();

    expect(
      await screen.findByText(/Record a ride with power or heart rate/),
    ).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Upload a ride" })).toHaveAttribute(
      "href",
      "/inbox",
    );
    const readout = screen.getByRole("region", { name: "Today" });
    for (const label of ["Fitness", "Fatigue", "Form"]) {
      expect(within(readout).getByText(label)).toBeVisible();
    }
    expect(
      within(readout).getAllByRole("img", { name: /^Not assessed: / }),
    ).toHaveLength(3);
    expect(within(readout).queryByText("0")).toBeNull();
    // No flat line of zeros either.
    expect(container.querySelector("canvas")).toBeNull();
    expect(constructions).toHaveLength(0);
  });

  it("gaps each line until its own series is first fed, never drawing zero", async () => {
    // The generated read: unpriced sessions first, priced gym sessions (ATL
    // fed) from day 7, priced rides (CTL, and so form) from day 15. The
    // series still starts on the first session; each line starts later.
    const served = rebased(FITNESS_TREND_LATE_PRICED);
    const firstFed = {
      ctl: served.maturity.ctl.first_priced_session,
      atl: served.maturity.atl.first_priced_session,
      tsb: served.maturity.tsb.first_assessed,
    };
    expect(firstFed.atl).not.toBeNull();
    expect(firstFed.ctl).not.toBeNull();
    expect(firstFed.atl).not.toBe(firstFed.ctl);
    expect(served.points[0]?.local_date).toBe(served.maturity.first_session);
    server.use(
      http.get("/api/v1/fitness", ({ response }) => response(200).json(served)),
    );
    renderFitness();

    await screen.findByRole("figure", { name: /Fitness, fatigue and form/ });

    const lines = plotted();
    for (const [label, key] of [
      ["Fitness (CTL)", "ctl"],
      ["Fatigue (ATL)", "atl"],
      ["Form (TSB)", "tsb"],
    ] as const) {
      const first = firstFed[key];
      if (first === null) throw new Error(`${key} is never fed`);
      const before = served.points.filter((point) => point.local_date < first);
      expect(before.length).toBeGreaterThan(0);
      // Only gaps before the series is fed — the domain's 0s never reach
      // the canvas — and the domain's own values from that day on.
      expect(lines.get(label)).toEqual(
        served.points.map((point) =>
          point.local_date < first ? null : point[key].value,
        ),
      );
    }
    // An unpriced session before fatigue was fed has no fatigue value to
    // mark; its day is named in words only.
    const marks = lines.get("Load incomplete") ?? [];
    served.points.forEach((point, index) => {
      if (firstFed.atl !== null && point.local_date < firstFed.atl) {
        expect(marks[index]).toBeNull();
      } else {
        expect(marks[index]).toBe(
          point.load_incomplete ? point.atl.value : null,
        );
      }
    });
    expect(
      served.points.some(
        (point) =>
          point.load_incomplete &&
          firstFed.atl !== null &&
          point.local_date >= firstFed.atl,
      ),
    ).toBe(true);
  });

  it("leaves fitness and form not assessed while only the gym is priced", async () => {
    // Read the day before the first priced ride: fatigue has load behind it,
    // fitness (cycling only) and form (fitness − fatigue) have none.
    const served = rebased(FITNESS_TREND_GYM_PRICED);
    expect(served.maturity.ctl.first_priced_session).toBeNull();
    expect(served.maturity.atl.first_priced_session).not.toBeNull();
    expect(served.maturity.tsb.first_assessed).toBeNull();
    server.use(
      http.get("/api/v1/fitness", ({ response }) => response(200).json(served)),
    );
    renderFitness();

    const readout = await screen.findByRole("region", { name: "Today" });
    const [last] = served.points.slice(-1);
    if (!last) throw new Error("the fixture has no points");
    expect(last.ctl.value).toBe(0);
    // Fixed slots, in order: Fitness, Fatigue, Form.
    const slots = Array.from(readout.children) as HTMLElement[];
    expect(
      slots.map(
        (slot) =>
          within(slot).getByText(/^(Fitness|Fatigue|Form)$/).textContent,
      ),
    ).toEqual(["Fitness", "Fatigue", "Form"]);
    const [fitness, fatigue, form] = slots;
    if (!fitness || !fatigue || !form) throw new Error("three slots");
    expect(
      within(fitness).getByRole("img", {
        name: "Not assessed: No ride with a power or heart-rate load yet",
      }),
    ).toBeVisible();
    expect(within(fatigue).getByText(last.atl.value.toFixed(0))).toBeVisible();
    expect(
      within(form).getByRole("img", { name: /^Not assessed: / }),
    ).toHaveAccessibleName(/fitness/);
    expect(within(readout).queryByText("0")).toBeNull();
    // The remedy names what is missing, and the action beside it.
    expect(screen.getByText(/Fitness counts rides only/)).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Upload a ride" })).toHaveAttribute(
      "href",
      "/inbox",
    );
    // Fatigue is drawn; fitness and form are gaps the whole way.
    const lines = plotted();
    expect(lines.get("Fitness (CTL)")?.every((value) => value === null)).toBe(
      true,
    );
    expect(lines.get("Form (TSB)")?.every((value) => value === null)).toBe(
      true,
    );
    expect(lines.get("Fatigue (ATL)")?.some((value) => value !== null)).toBe(
      true,
    );
  });

  it("shows an error, not a blank panel, when the read fails", async () => {
    server.use(
      http.untyped.get("http://localhost:8000/api/v1/fitness", () =>
        Response.json({ detail: "boom" }, { status: 500 }),
      ),
    );
    const { container } = renderFitness();

    const alert = await screen.findByRole("alert");
    expect(alert).toHaveTextContent(/fitness series/);
    expect(container.querySelector("canvas")).toBeNull();
    // The badge still says what kind of number this page would have shown.
    expect(screen.getByRole("note", { name: "Display-only" })).toBeVisible();
  });
});
